"""tools/trailer/beats.py: the beats of Lace's battle theme the trailer cuts on, into stage/beats.js.
    uvx --with librosa python -I tools/trailer/beats.py <cache>/lace.wav tools/trailer/stage/beats.js
The video uses the theme's loud section from 56.91 s (its first hit, at the video's 0.80 s) to the
drop at 87.89 s, and fades out after it: 152.1 bpm, a beat every 0.394 s. Its sections, by
librosa's segmentation (15-Oct-2026): 56.91 (the hit Hornet lands on), 73.79 (Progress), 80.04
(the montage), 82.01 (the loudest bar: the 100%), 87.89 (the end card). Run again only if the
track or the cut changes: beats.js is kept in the repo, so a render needs no librosa. """
import json, sys
import librosa

START = 56.91 - 0.8   # the track's time at the video's 0

y, sr = librosa.load(sys.argv[1], sr=22050, mono=True)
_, frames = librosa.beat.beat_track(y=y, sr=sr)
beats = [round(float(b) - START, 4) for b in librosa.frames_to_time(frames, sr=sr) if START - 0.5 <= b <= START + 40]
with open(sys.argv[2], 'w') as fh:
    fh.write('/* stage/beats.js: GENERATED by tools/trailer/beats.py from Lace\'s battle theme: each beat, in the\n'
             '   video\'s seconds (BEATS[3] is the first hit, 0.80 s), and the track\'s time at the video\'s 0. */\n')
    fh.write('window.BEATS=' + json.dumps(beats) + ';window.AUDIO_START=' + str(round(START, 4)) + ';\n')
print(f'{len(beats)} beats, the first hit at {beats[3]:.3f} s')
