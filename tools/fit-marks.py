"""tools/fit-marks.py: how big each picture a Map mark can show really is, so every mark draws its
picture at the same visible size (design/03-redesign.md, step 6, the marks' size). The pictures come
from different sources (the inventory's icons, the Journal's portraits, the map's pins and icons, the
people's heads), each with its own transparent margin: drawn in one box, the Mask Shard filled half
the disc and a pilgrim's head spilled past its rim. This measures the opaque part of each one (alpha
over THRESHOLD) and writes js/mark-fit.js, which js/app-map.js reads to place it (fitOf there): its
opaque box centred, its longest side a set share of the disc, shrunk just enough that no opaque
pixel crosses the plate.
One command, after any picture under the folders below changes (npm run icons, npm run art, the
extract-*.py tools):
    npm run mark-fit          (python3 tools/fit-marks.py; needs Pillow)
For each picture, in its own pixels: [width, height, the opaque box's centre x, y, its longest side,
the farthest opaque pixel from that centre], and for one the Map draws turned (ROTATED) the longest
side of its opaque box once turned. The Vesticrest's slot signs (Eva's marks) are inline pictures in
js/crest-slots.js, not files: they go in as 'crest:<colour>'. test/mark-fit.test.js fails when a
picture has no line here or a line has no picture. """
import base64
import io
import json
import math
import os
import re
import sys

from PIL import Image

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
OUT = os.path.join(ROOT, 'js', 'mark-fit.js')
THRESHOLD = 40            # alpha (0-255) over which a pixel counts as the picture's
# Every folder a mark, its legend picture or a list's mark takes its picture from (js/app-map.js).
FOLDERS = ['assets/icons/arts', 'assets/icons/crests', 'assets/icons/extras', 'assets/icons/items',
           'assets/icons/journal', 'assets/icons/pieces', 'assets/icons/skills', 'assets/icons/tools',
           'assets/map/pins', 'assets/map/icons', 'assets/map/people', 'assets/crests']
# The pictures the Map draws turned, and by how much (degrees, clockwise): the Needle, a long thin line
# laid across the disc (artOf in js/app-map.js).
ROTATED = {'assets/icons/items/needle.webp': 35}
CREST_SIGNS = ['red', 'blue', 'yellow', 'skill']


def measure(im, turn=0):
    im = im.convert('RGBA')
    W, H = im.size
    mask = im.getchannel('A').point(lambda a: 255 if a > THRESHOLD else 0)
    box = mask.getbbox() or (0, 0, W, H)
    cx, cy = (box[0] + box[2]) / 2, (box[1] + box[3]) / 2
    px = mask.load()
    far = 0.0
    for y in range(box[1], box[3]):
        for x in range(box[0], box[2]):
            if px[x, y]:
                far = max(far, math.hypot(x + 0.5 - cx, y + 0.5 - cy))
    row = [W, H, round(cx, 1), round(cy, 1), max(box[2] - box[0], box[3] - box[1]), round(far, 1)]
    if turn:
        t = mask.rotate(-turn, expand=True, resample=Image.BICUBIC).point(lambda a: 255 if a > 127 else 0).getbbox()
        row.append(max(t[2] - t[0], t[3] - t[1]))
    return row


def main():
    fit = {}
    for folder in FOLDERS:
        for name in sorted(os.listdir(os.path.join(ROOT, folder))):
            if name.endswith('.webp'):
                src = folder + '/' + name
                fit[src] = measure(Image.open(os.path.join(ROOT, src)), ROTATED.get(src, 0))
    slots = open(os.path.join(ROOT, 'js', 'crest-slots.js'), encoding='utf-8').read()
    for k in CREST_SIGNS:
        m = re.search(r'"%s":\["data:image/webp;base64,([^"]+)"' % k, slots)
        if not m:
            sys.exit('js/crest-slots.js has no %s sign: run tools/extract-crests.py first' % k)
        fit['crest:' + k] = measure(Image.open(io.BytesIO(base64.b64decode(m.group(1)))))
    lines = ',\n'.join('    %s: %s' % (json.dumps(k), json.dumps(v)) for k, v in fit.items())
    js = f"""/* js/mark-fit.js: how big each picture a Map mark can show really is, in its own pixels:
   [width, height, its opaque box's centre x, y, that box's longest side, the farthest opaque pixel
   from its centre(, the box's longest side once turned as the Map draws it)]. js/app-map.js (fitOf)
   draws every picture from it at the same visible size (design/03-redesign.md, step 6, the marks'
   size). The Vesticrest's slot signs are 'crest:<colour>'.
   GENERATED by tools/fit-marks.py (npm run mark-fit) from the pictures themselves: not edited by hand. */
(() => {{
  const SS = globalThis.SS || (globalThis.SS = {{}});
  SS.markFit = {{
{lines},
  }};
  if (typeof module !== 'undefined' && module.exports) module.exports = SS.markFit;
}})();
"""
    with open(OUT, 'w', encoding='utf-8') as f:
        f.write(js)
    print('js/mark-fit.js: %d pictures' % len(fit))


if __name__ == '__main__':
    main()
